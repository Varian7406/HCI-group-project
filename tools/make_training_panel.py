def cell_box(col: int, row: int):
    x0 = MARGIN_X + col * (CELL_W + GAP)
    y0 = TOP + row * (CELL_H + GAP)
    return x0, y0, x0 + CELL_W, y0 + CELL_H


def bounds_for(col: int, row: int):
    x0, y0, x1, y1 = cell_box(col, row)
    return [round(x0 / W, 4), round(y0 / H, 4), round(x1 / W, 4), round(y1 / H, 4)]


