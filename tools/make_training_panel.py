def components_json():
    out = []
    for cid, label, kind, col, row, extra in PANEL:
        item = {"id": cid, "label": label, "kind": kind, "bounds": bounds_for(col, row)}
        item.update(extra)
        out.append(item)
    return out


def procedure_json(pid: str) -> dict:
    """Emit a procedure dict in the schema project11.procedure_loader expects."""
    spec = VARIANTS[pid]
    hz = HAZARDS["practice" if pid == "practice" else "main"]
    return {
        "schema_version": 1,
        "procedure_id": pid,
        "content_version": CONTENT_VERSION,
        "image": IMAGE_REL,
        "source": SOURCE,
        "components": components_json(),
        "steps": spec["steps"],
        "hazard": {
            # Our loader arms the hazard as soon as this step is COMPLETED
            # (Claude's draft also had a delay_ms before it appears; that is
            # dropped here because the loader has no delay field).
            "trigger_after_step": hz["trigger"]["step_id"],
            "message": hz["message"],
            "correct_component_id": hz["response_component_id"],
            "response_window_ms": hz["response_window_ms"],
        },
    }


def travel(pid: str) -> float:
    """Total straight-line distance (source pixels) between consecutive step targets."""
    centres = {cid: (MARGIN_X + c * (CELL_W + GAP) + CELL_W / 2, TOP + r * (CELL_H + GAP) + CELL_H / 2)
               for cid, _l, _k, c, r, _e in PANEL}
    pts = [centres[st["component_id"]] for st in VARIANTS[pid]["steps"]]
    return sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))


def main() -> None:
    (ASSETS / "images").mkdir(parents=True, exist_ok=True)
    (ASSETS / "procedures").mkdir(parents=True, exist_ok=True)
    build_image().save(ASSETS / IMAGE_REL)
    for pid in VARIANTS:
        path = ASSETS / "procedures" / f"{pid}.json"
        path.write_text(json.dumps(procedure_json(pid), indent=2) + "\n", encoding="utf-8")
        extra = f"   cursor travel {travel(pid):.0f} px" if pid != "practice" else ""
        print(f"wrote {path.relative_to(ROOT)}{extra}")
    # The app's MainWindow loads example_procedure.json by default, so write
    # variant 1 there too (under the neutral id) and the app just works.
    example = procedure_json("variant_1")
    example["procedure_id"] = "training_panel_01"
    (ASSETS / "procedures" / "example_procedure.json").write_text(
        json.dumps(example, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {(ASSETS / 'procedures' / 'example_procedure.json').relative_to(ROOT)}"
          "  (copy of variant_1, so the app runs out of the box)")
    print(f"wrote {(ASSETS / IMAGE_REL).relative_to(ROOT)}")
    print("Variants share the same 8-step shape and nearly the same travel; whether they are equally "
          "hard for people is what the pilot has to check.")


if __name__ == "__main__":
    main()
