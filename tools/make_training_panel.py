def build_image() -> Image.Image:
    img = Image.new("RGB", (W, H), "#aab4c3")
    d = ImageDraw.Draw(img)
    f_title, f_small = load_font(30, True), load_font(18)
    f_label, f_icon = load_font(21, True), load_font(18, True)

    d.rectangle((0, 0, W, TOP - 24), fill="#232a36")
    d.text((40, 38), "TRAINING PANEL TP-01", font=f_title, fill="#f9fafb", anchor="lm")
    d.text((W - 40, 38), "FICTIONAL SIMULATION - NOT REAL MAINTENANCE ADVICE",
           font=f_small, fill="#fcd34d", anchor="rm")
    d.rectangle((0, H - BOTTOM + 14, W, H), fill="#232a36")
    d.text((40, H - 18), "Fictional training panel for a research simulation. All steps are illustrative.",
           font=f_small, fill="#d1d5db", anchor="lm")

    for cid, label, kind, col, row, _extra in PANEL:
        x0, y0, x1, y1 = cell_box(col, row)
        stop = cid == "emergency_stop"
        d.rounded_rectangle((x0, y0, x1, y1), 16, fill="#fde8e8" if stop else "#e6eaf0",
                            outline="#b91c1c" if stop else "#566174", width=5 if stop else 3)
        cx, cy = (x0 + x1) / 2, y0 + CELL_H * 0.42
        if cid == "pressure_gauge":
            draw_gauge(d, cx, cy, 300)
        elif cid == "temp_gauge":
            draw_gauge(d, cx, cy, 215)
        elif cid in ("power_switch",):
            draw_switch(d, cx, cy)
        elif cid == "valve_lever":
            draw_valve(d, cx - 6, cy + 8)
        elif cid == "mode_selector":
            draw_selector(d, cx, cy)
        elif cid == "connector_a":
            draw_connector(d, cx, cy, 6)
        elif cid == "connector_b":
            draw_connector(d, cx, cy, 4)
        elif cid == "fuse_holder":
            draw_fuse(d, cx, cy)
        elif cid == "battery_pack":
            draw_battery(d, cx, cy, f_label)
        elif cid == "filter_cartridge":
            draw_filter(d, cx, cy)
        elif cid == "cover_panel":
            draw_cover(d, cx, cy)
        elif cid == "service_port":
            draw_port(d, cx, cy)
        elif cid == "reset_button":
            draw_button(d, cx, cy, "RESET", "#2563eb", f_icon)
        elif cid == "test_button":
            draw_button(d, cx, cy, "TEST", "#047857", f_icon)
        elif stop:
            draw_estop(d, cx, cy)
        d.text(((x0 + x1) / 2, y1 - 24), label, font=fit_font(d, label, CELL_W - 22),
               fill="#7f1d1d" if stop else "#1f2937", anchor="mm")
    return img


